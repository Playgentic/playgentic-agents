#!/usr/bin/env node
// Generates per-provider agent definitions from the single source in src/agents/.
//
//   node scripts/build.mjs
//
// Outputs (never edit by hand, CI fails if they drift from src/):
//   agents/<name>.md                          Claude Code subagents
//   com.github.copilot/agents/<name>.agent.md GitHub Copilot custom agents
//   skills/author-tests/agents/<name>.md      plain briefs, for harnesses that can't ship
//                                             plugin agents (Codex): the orchestrator spawns
//                                             a generic subagent with this as its instructions
//
// Source frontmatter: name, description, access (read|write), tools (neutral tags), model, color.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src", "agents");
const PLUGIN = JSON.parse(readFileSync(join(ROOT, ".claude-plugin", "plugin.json"), "utf8")).name;
// The generic Playwright MCP (@playwright/mcp). Tests run through the shell, not MCP.
const MCP_SERVER = "playwright";

const BROWSER_TOOLS = [
  "browser_snapshot", "browser_navigate", "browser_click", "browser_type", "browser_fill_form",
  "browser_select_option", "browser_hover", "browser_press_key",
  "browser_wait_for", "browser_console_messages", "browser_close",
];

// Claude namespaces plugin MCP tools as mcp__plugin_<plugin>_<server>__<tool>.
const claudeMcp = (t) => `mcp__plugin_${PLUGIN}_${MCP_SERVER}__${t}`;
const CLAUDE_TOOLS = {
  read: ["Read"],
  search: ["Glob", "Grep"],
  edit: ["Write", "Edit"],
  shell: ["Bash"],
  browser: BROWSER_TOOLS.map(claudeMcp),
};

const header = (comment) => `${comment} GENERATED by scripts/build.mjs from src/agents/. Edit the source, then rebuild.`;

function parse(file) {
  const text = readFileSync(file, "utf8");
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    const [, k, v] = kv;
    meta[k] = v.startsWith("[") ? v.slice(1, -1).split(",").map((s) => s.trim()).filter(Boolean) : v;
  }
  for (const k of ["name", "description", "access", "tools"]) {
    if (!meta[k]) throw new Error(`${file}: frontmatter needs "${k}"`);
  }
  for (const t of meta.tools) {
    if (!CLAUDE_TOOLS[t]) throw new Error(`${file}: unknown tool tag "${t}"`);
  }
  if (meta.access === "read" && meta.tools.includes("edit")) {
    throw new Error(`${file}: access: read cannot include the edit tool`);
  }
  return { meta, body: m[2].replace(/^\n+/, "") };
}

const readOnlyNote = (meta) =>
  meta.access === "read" ? "> **Read-only.** Never create, edit, or delete files. Your final message is your output.\n\n" : "";

function claude({ meta, body }) {
  const tools = meta.tools.flatMap((t) => CLAUDE_TOOLS[t]).join(", ");
  return [
    "---",
    `name: ${meta.name}`,
    `description: ${meta.description}`,
    `tools: ${tools}`,
    ...(meta.model ? [`model: ${meta.model}`] : []),
    ...(meta.color ? [`color: ${meta.color}`] : []),
    "---",
    `<!-- ${header("").trim()} -->`,
    "",
    body,
  ].join("\n");
}

// Copilot's tools aliases aren't stable across surfaces yet, so no `tools:` list:
// the agent gets everything and the read-only constraint is stated in the prompt.
function copilot({ meta, body }) {
  return [
    "---",
    `name: ${meta.name}`,
    `description: ${JSON.stringify(meta.description)}`,
    "---",
    `<!-- ${header("").trim()} -->`,
    "",
    readOnlyNote(meta) + body,
  ].join("\n");
}

function brief({ meta, body }) {
  return [
    `<!-- ${header("").trim()} -->`,
    `# ${meta.name} agent brief`,
    "",
    `_${meta.description}_`,
    "",
    readOnlyNote(meta) + body,
  ].join("\n");
}

const outputs = [
  { dir: join(ROOT, "agents"), ext: ".md", render: claude },
  { dir: join(ROOT, "com.github.copilot", "agents"), ext: ".agent.md", render: copilot },
  { dir: join(ROOT, "skills", "author-tests", "agents"), ext: ".md", render: brief },
];

const sources = readdirSync(SRC).filter((f) => f.endsWith(".md")).sort();
for (const f of sources) {
  const agent = parse(join(SRC, f));
  for (const { dir, ext, render } of outputs) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, agent.meta.name + ext), render(agent));
  }
  console.log(`built ${agent.meta.name}`);
}
